"""Generate the C level header from the Python level definition.

The Python module is the single source of truth for geometry and wave data.
This script writes components/app_game/data/frostline_level.h so the model
and the art can never drift apart.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from artgen import level_geom as geom
from artgen import tower_data as tower  # noqa: E402

HEADER = """/* Generated by assets_src/artgen/generate_level.py -- do not edit by hand.
 *
 * Source of truth: assets_src/artgen/level_geom.py
 * Regenerate with: python3 assets_src/artgen/generate_level.py
 */
#ifndef FROSTLINE_LEVEL_H
#define FROSTLINE_LEVEL_H

#include <stdint.h>

#include "../include/frostline_model.h"

#define FL_PLAY_TOP {play_top}
#define FL_PLAY_BOTTOM {play_bottom}

#define FL_LANE_A_POINTS {lane_a_count}
#define FL_LANE_B_POINTS {lane_b_count}
#define FL_MERGE_DISTANCE {merge_distance:.2f}f

#define FL_BUILD_SPOT_COUNT {spot_count}
#define FL_HERO_POST_COUNT 2
#define FL_WAVE_COUNT {wave_count}
#define FL_ENEMY_KIND_COUNT {enemy_kind_count}
#define FL_BATCH_MAX {batch_max}

#define FL_TOWER_KIND_COUNT {tower_kind_count}
#define FL_TOWER_LEVEL_COUNT {tower_level_count}
#define FL_TOWER_STAGE_COUNT {tower_stage_count}
#define FL_TOWER_OPTION_COUNT {tower_option_count}

#define FL_FIRST_PREP_TICKS {first_prep}
#define FL_PREP_TICKS {prep}

/* fl_point_t comes from frostline_model.h, included above. */
static const fl_point_t FL_LANE_A[FL_LANE_A_POINTS] = {{
{lane_a}
}};

static const fl_point_t FL_LANE_B[FL_LANE_B_POINTS] = {{
{lane_b}
}};

static const fl_point_t FL_GOAL = {{{goal_x}, {goal_y}}};
static const fl_point_t FL_SPAWN = {{{spawn_x}, {spawn_y}}};

static const fl_point_t FL_BUILD_SPOTS[FL_BUILD_SPOT_COUNT] = {{
{spots}
}};

static const fl_point_t FL_HERO_POSTS[FL_HERO_POST_COUNT] = {{
{posts}
}};

/* Enemy roster: kind, hp, armor, speed in px/s, bounty, score, behaviour,
 * and the pixel size of its sprite. */
typedef struct {{
    int16_t hp;
    int16_t armor;
    int16_t speed;
    int16_t bounty;
    int16_t score;
    uint8_t behaviour;
    uint8_t size;
}} fl_enemy_stat_t;

static const fl_enemy_stat_t FL_ENEMY_STATS[FL_ENEMY_KIND_COUNT] = {{
{enemies}
}};

/* One level of a tower. "cost" is the price of building it outright;
 * "upgrade" is the price of moving up from the level below. */
typedef struct {{
    int16_t damage;
    int16_t range;
    uint16_t cooldown;
    int16_t aoe;
    uint16_t projectile_speed;
    uint16_t cost;
    uint16_t upgrade;
}} fl_tower_level_t;

/* A specialisation offered at one upgrade stage. The chosen ones stack. */
typedef struct {{
    int16_t damage_mult;   /* percent on the level damage */
    int16_t range_delta;   /* flat pixels */
    int16_t cooldown_mult; /* percent on the reload time */
    int16_t aoe_delta;     /* flat pixels */
    int16_t slow_mult;     /* percent on the slow factor */
    uint8_t pierce;        /* the shot ignores armour */
    uint8_t burn;          /* the shot sets the target burning */
    uint8_t stun;          /* the shot stops the target */
    uint8_t double_shot;   /* the shot also hits a second enemy */
}} fl_tower_mod_t;

static const fl_tower_level_t FL_TOWER_LEVELS[FL_TOWER_KIND_COUNT][FL_TOWER_LEVEL_COUNT] = {{
{tower_levels}
}};

/* [kind][stage][option]; stage 0 is level 1->2, stage 1 is level 2->3. */
static const fl_tower_mod_t FL_TOWER_MODS[FL_TOWER_KIND_COUNT][FL_TOWER_STAGE_COUNT][FL_TOWER_OPTION_COUNT] = {{
{tower_mods}
}};

/* The printed name of every upgrade option, for the upgrade panel. */
static const char *const FL_TOWER_MOD_NAMES[FL_TOWER_KIND_COUNT][FL_TOWER_STAGE_COUNT][FL_TOWER_OPTION_COUNT] = {{
{tower_mod_names}
}};

/* One spawn batch inside a wave. */
typedef struct {{
    uint8_t kind;
    uint8_t count;
    uint8_t interval;
    uint8_t lane;
}} fl_batch_t;

typedef struct {{
    uint16_t reward;
    uint16_t score_bonus;
    uint16_t hp_mult;      /* percent of the base health for this wave */
    uint16_t armor_add;    /* armour added to every enemy in this wave */
    uint8_t batch_count;
    fl_batch_t batches[FL_BATCH_MAX];
}} fl_wave_t;

static const fl_wave_t FL_WAVES[FL_WAVE_COUNT] = {{
{waves}
}};

#endif
"""


def _points(points):
    return "\n".join("    {%d, %d}," % (x, y) for x, y in points)


def _enemies():
    rows = []
    for _kind, _name, hp, armor, speed, bounty, score, behaviour, size in geom.ENEMY_STATS:
        rows.append("    {%d, %d, %d, %d, %d, %d, %d},"
                    % (hp, armor, speed, bounty, score, behaviour, size))
    return "\n".join(rows)


def _waves():
    rows = []
    for wave in geom.WAVES:
        batches = "".join(
            "{%d, %d, %d, %d}, " % batch for batch in wave["batches"]
        )
        rows.append("    {%d, %d, %d, %d, %d, {%s}},"
                    % (wave["reward"], wave["score_bonus"], wave["hp_mult"],
                       wave["armor_add"], len(wave["batches"]), batches))
    return "\n".join(rows)


def _tower_levels():
    """[kind][level]: one nested block per tower kind."""
    empty = "{0, 0, 0, 0, 0, 0, 0}"
    blocks = ["    {%s}," % ", ".join([empty] * tower.TOWER_LEVEL_COUNT)]
    for kind in tower.TOWER_ORDER:
        rows = []
        for level in tower.tower_levels(kind):
            rows.append("{%d, %d, %d, %d, %d, %d, %d}" % (
                level["damage"], level["range"], level["cooldown"],
                level["aoe"], level["speed"], level["cost"], level["upgrade"]))
        blocks.append("    {%s}," % ", ".join(rows))
    return "\n".join(blocks)


def _tower_mods():
    """[kind][stage][option]: two nested stages per kind."""
    empty = "{0, 0, 0, 0, 0, 0, 0, 0, 0}"
    pad_stage = "{%s}" % ", ".join([empty] * tower.TOWER_OPTION_COUNT)
    blocks = ["    {%s}," % ", ".join([pad_stage] * tower.TOWER_STAGE_COUNT)]
    for kind in tower.TOWER_ORDER:
        stages = []
        for stage in range(tower.TOWER_STAGE_COUNT):
            options = []
            for option in tower.tower_mods(kind, stage):
                options.append("{%d, %d, %d, %d, %d, %d, %d, %d, %d}" % (
                    option["damage_mult"], option["range_delta"],
                    option["cooldown_mult"], option["aoe_delta"],
                    option["slow_mult"], option["pierce"], option["burn"],
                    option["stun"], option["double_shot"]))
            stages.append("{%s}" % ", ".join(options))
        blocks.append("    {%s}," % ", ".join(stages))
    return "\n".join(blocks)


def _tower_mod_names():
    """[kind][stage][option]: the printed name of every upgrade."""
    blocks = ['    {%s},'
              % ", ".join(['{"", ""}'] * tower.TOWER_STAGE_COUNT)]
    for kind in tower.TOWER_ORDER:
        stages = []
        for stage in range(tower.TOWER_STAGE_COUNT):
            options = ["\"%s\"" % option["name"]
                       for option in tower.tower_mods(kind, stage)]
            stages.append("{%s}" % ", ".join(options))
        blocks.append("    {%s}," % ", ".join(stages))
    return "\n".join(blocks)


def _cumulative(points):
    total = [0.0]
    for index in range(1, len(points)):
        ax, ay = points[index - 1]
        bx, by = points[index]
        total.append(total[-1] + ((bx - ax) ** 2 + (by - ay) ** 2) ** 0.5)
    return total


def render():
    lane_a = geom.PATH_LANE_A_ROUTE
    lane_b = geom.PATH_LANE_B_ROUTE
    cumulative = _cumulative(lane_a)
    # The rounded lane no longer passes exactly through the corner, so the
    # merge point is the closest sample on lane A to where lane B ends.
    target = lane_b[-1]
    merge_index = min(range(len(lane_a)),
                       key=lambda i: (lane_a[i][0] - target[0]) ** 2
                       + (lane_a[i][1] - target[1]) ** 2)
    merge_distance = cumulative[merge_index]
    return HEADER.format(
        play_top=geom.PLAY_TOP,
        play_bottom=geom.PLAY_BOTTOM,
        lane_a_count=len(geom.PATH_LANE_A_ROUTE),
        lane_b_count=len(geom.PATH_LANE_B_ROUTE),
        merge_distance=merge_distance,
        spot_count=len(geom.BUILD_SPOTS),
        wave_count=geom.WAVE_COUNT,
        enemy_kind_count=len(geom.ENEMY_STATS),
        first_prep=geom.FIRST_PREP_TICKS,
        prep=geom.PREP_TICKS,
        lane_a=_points(lane_a),
        lane_b=_points(lane_b),
        goal_x=geom.GOAL[0], goal_y=geom.GOAL[1],
        spawn_x=geom.SPAWN[0], spawn_y=geom.SPAWN[1],
        spots=_points(geom.BUILD_SPOTS),
        posts=_points(geom.HERO_POSTS),
        enemies=_enemies(),
        waves=_waves(),
        batch_max=geom.BATCH_MAX,
        tower_kind_count=tower.TOWER_KIND_COUNT,
        tower_level_count=tower.TOWER_LEVEL_COUNT,
        tower_stage_count=tower.TOWER_STAGE_COUNT,
        tower_option_count=tower.TOWER_OPTION_COUNT,
        tower_levels=_tower_levels(),
        tower_mods=_tower_mods(),
        tower_mod_names=_tower_mod_names(),
    )


def target_path():
    return HERE.parent.parent / "components" / "app_game" / "data" / "frostline_level.h"


def main():
    out = target_path()
    out.parent.mkdir(parents=True, exist_ok=True)
    text = render()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("frostline_level.h is out of date", file=sys.stderr)
            return 1
        print("frostline_level.h is up to date")
        return 0
    out.write_text(text, encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
