"""Bake every battlefield and the campaign map into a 1-bit C header.

The terrain is strictly two-tone, so it is stored as one bit per pixel
(MSB first, 1 = ink) and compiled into the firmware. The runtime expands
only the map on screen into RGB565, which keeps 22 levels plus a long
campaign scroll in about 700 KB of flash instead of a 10 MB texture atlas.

Building the maps takes a while, so the header records a hash of every
input; --check compares hashes and never redraws anything.

Regenerate with: python3 assets_src/artgen/generate_terrain.py
"""
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from artgen import levels as campaign  # noqa: E402
from artgen.ai_terrain import (  # noqa: E402
    AI_DIR, CASTLE_SOURCE, build_campaign_background, build_level_background,
)
from artgen.canvas import BLACK  # noqa: E402

MAP_SIZE = 480
BYTES_PER_LINE = 24

# Everything the drawing depends on: the generators and the AI plates.
CODE_INPUTS = ("ai_terrain.py", "canvas.py", "shade.py", "levels.py",
               "level_kit.py", "interludes.py", "level_geom.py",
               "generate_terrain.py")


def _plates():
    names = [level["plate"] for level in campaign.LEVELS]
    names += list(campaign.CAMPAIGN_PLATES)
    names.append(CASTLE_SOURCE.name)
    return sorted(set(names))


def inputs_hash():
    digest = hashlib.sha256()
    for name in CODE_INPUTS:
        digest.update(name.encode())
        digest.update((HERE / name).read_bytes())
    for name in _plates():
        digest.update(name.encode())
        digest.update((AI_DIR / name).read_bytes())
    return digest.hexdigest()


def pack_bits(canvas):
    """Rows of MSB-first bytes; a set bit is ink."""
    assert canvas.width % 8 == 0
    out = bytearray()
    for y in range(canvas.height):
        for x0 in range(0, canvas.width, 8):
            byte = 0
            for bit in range(8):
                if canvas.get(x0 + bit, y) == BLACK:
                    byte |= 0x80 >> bit
            out.append(byte)
    return bytes(out)


def _c_bytes(data, indent="    "):
    lines = []
    for start in range(0, len(data), BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append(indent + ",".join("0x%02X" % b for b in chunk) + ",")
    return "\n".join(lines)


def render(digest):
    levels = campaign.LEVELS
    maps = []
    for level in levels:
        canvas = build_level_background(level)
        assert (canvas.width, canvas.height) == (MAP_SIZE, MAP_SIZE)
        maps.append((level["key"], pack_bits(canvas)))
    scroll = build_campaign_background()
    assert scroll.width == campaign.CAMPAIGN_WIDTH and scroll.height == MAP_SIZE

    parts = [
        "/* Generated by assets_src/artgen/generate_terrain.py. Do not edit.",
        " * inputs-sha256: %s" % digest,
        " *",
        " * One bit per pixel, MSB first, 1 = ink. Regenerate with:",
        " *   python3 assets_src/artgen/generate_terrain.py",
        " */",
        "#ifndef FROSTLINE_TERRAIN_DATA_H",
        "#define FROSTLINE_TERRAIN_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "#define FL_TERRAIN_SIZE %d" % MAP_SIZE,
        "#define FL_TERRAIN_MAP_COUNT %d" % len(maps),
        "#define FL_TERRAIN_MAP_BYTES %d" % (MAP_SIZE * MAP_SIZE // 8),
        "#define FL_TERRAIN_CAMPAIGN_W %d" % scroll.width,
        "",
        "/* One battlefield per level, in play order. */",
        "static const uint8_t FL_TERRAIN_MAPS[FL_TERRAIN_MAP_COUNT]"
        "[FL_TERRAIN_MAP_BYTES] = {",
    ]
    for key, data in maps:
        parts.append("    { /* %s */" % key)
        parts.append(_c_bytes(data, "        "))
        parts.append("    },")
    parts += [
        "};",
        "",
        "/* The campaign scroll, FL_TERRAIN_CAMPAIGN_W x FL_TERRAIN_SIZE. */",
        "static const uint8_t FL_TERRAIN_CAMPAIGN"
        "[FL_TERRAIN_CAMPAIGN_W * FL_TERRAIN_SIZE / 8] = {",
        _c_bytes(pack_bits(scroll)),
        "};",
        "",
        "#endif",
        "",
    ]
    return "\n".join(parts)


def target_path():
    return (HERE.parent.parent / "components" / "app_game_runtime" / "data"
            / "frostline_terrain_data.h")


def recorded_hash(path):
    if not path.exists():
        return None
    with path.open(encoding="utf-8") as handle:
        for _ in range(4):
            line = handle.readline()
            if "inputs-sha256:" in line:
                return line.split("inputs-sha256:")[1].strip()
    return None


def main():
    out = target_path()
    digest = inputs_hash()
    if "--check" in sys.argv:
        if recorded_hash(out) != digest:
            print("frostline_terrain_data.h is out of date", file=sys.stderr)
            return 1
        print("frostline_terrain_data.h is up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(digest), encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
