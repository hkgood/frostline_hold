"""Generate the C tower rig header from artgen/tower_rig.py.

The rig is where the moving parts of each tower sprite sit: the model fires
from its muzzle points and the view hangs ammunition, spare pots and orbiting
stones on the rest, so a shot always leaves the part the art shows.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from artgen import tower_data as tower  # noqa: E402
from artgen import tower_rig as rig  # noqa: E402

HEADER = """/* Generated by assets_src/artgen/generate_tower_rig.py -- do not edit by hand.
 *
 * Source of truth: assets_src/artgen/tower_rig.py, which the tower art is
 * drawn to. Regenerate with: python3 assets_src/artgen/generate_tower_rig.py
 *
 * A point is px right of a tower's foot (for a tower facing right) and px
 * above it. Parts a look does not have are {{0, 0}}.
 */
#ifndef FROSTLINE_TOWER_RIG_H
#define FROSTLINE_TOWER_RIG_H

#include <stdint.h>

#define FL_TOWER_VARIANTS {variants}
#define FL_GUARD_DIRECTIONS {guard_directions}

typedef struct {{
    int8_t dx;
    int8_t h;
}} fl_rig_point_t;

typedef struct {{
    fl_rig_point_t muzzle;   /* where its shot leaves it */
    fl_rig_point_t load;     /* the catapult's shot, waiting in the bucket */
    fl_rig_point_t spare[2]; /* the kiln's waiting fire pots */
    fl_rig_point_t door;     /* the hall's doorway, bottom centre */
    uint8_t orbit_count;     /* stones or shards circling the tower */
    int8_t orbit_rx, orbit_ry, orbit_h;
    int8_t charge_h;         /* where a gathering charge starts to climb */
}} fl_tower_rig_t;

/* [kind][variant]: level 1, level 2, then the two level 3 branches. */
static const fl_tower_rig_t FL_TOWER_RIGS[{kind_count}][FL_TOWER_VARIANTS] = {{
{rigs}
}};

/* Per kind: how far the bolt tip sits ahead of a turning head's mount, and
 * whether the whole sprite faces left or right after its target. */
static const int8_t FL_TOWER_REACH[{kind_count}] = {{{reach}}};
static const uint8_t FL_TOWER_MIRRORS[{kind_count}] = {{{mirrors}}};

#endif
"""


def _point(point):
    return "{%d, %d}" % point


def _rig_entry(entry):
    count, rx, ry, h = entry["orbit"]
    return "{%s, %s, {%s, %s}, %s, %d, %d, %d, %d, %d}" % (
        _point(entry["muzzle"]), _point(entry["load"]),
        _point(entry["spare"][0]), _point(entry["spare"][1]),
        _point(entry["door"]), count, rx, ry, h, entry["charge"])


def render():
    empty = _rig_entry(rig._rig("", 0))
    blocks = ["    {%s}," % ", ".join([empty] * len(rig.VARIANTS))]
    for kind in tower.TOWER_ORDER:
        rows = ",\n".join("        " + _rig_entry(entry)
                          for entry in rig.tower_rigs(kind))
        blocks.append("    /* %s */\n    {\n%s,\n    }," % (kind, rows))
    kinds = ("",) + tower.TOWER_ORDER
    return HEADER.format(
        variants=len(rig.VARIANTS),
        guard_directions=rig.GUARD_DIRECTIONS,
        kind_count=tower.TOWER_KIND_COUNT,
        rigs="\n".join(blocks),
        reach=", ".join(str(rig.REACH.get(kind, 0)) for kind in kinds),
        mirrors=", ".join("1" if rig.TURNS.get(kind) == "mirror" else "0"
                          for kind in kinds),
    )


def target_path():
    return (HERE.parent.parent / "components" / "app_game" / "data"
            / "frostline_tower_rig.h")


def main():
    out = target_path()
    text = render()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("frostline_tower_rig.h is out of date", file=sys.stderr)
            return 1
        print("frostline_tower_rig.h is up to date")
        return 0
    out.write_text(text, encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
